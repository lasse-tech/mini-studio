function playTheme() {
    for (let i = 0; i < melody.length; i += 2) {
        const frequency = melody[i]
        const length = melody[i + 1]
        if (frequency == 0) {
            basic.clearScreen()
            music.rest(length)
            continue
        }
        // Interval 0: showLeds pauses 400 ms by default
        if (i % 4 == 0) {
            basic.showLeds(`
                . # # # .
                # . . . #
                # . # . #
                # . . . #
                . # # # .
            `, 0)
        } else {
            basic.showLeds(`
                . . # . .
                . # . # .
                # . # . #
                . # . # .
                . . # . .
            `, 0)
        }
        const sound = Math.idiv(length * 95, 100)
        music.playTone(frequency, sound)
        basic.clearScreen()
        music.rest(length - sound)
    }
}

input.onButtonPressed(Button.A, function () {
    playTheme()
})

